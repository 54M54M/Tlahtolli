-- ============================================================
--  1. LANGUAGES
-- ============================================================
CREATE TABLE LANGUAGES (
    ID              NUMBER          GENERATED ALWAYS AS IDENTITY NOT NULL,
    CODE            VARCHAR2(10)    NOT NULL,
    LANG_NAME       VARCHAR2(100)   NOT NULL,
    NATIVE_NAME     VARCHAR2(100),
    COLOR           VARCHAR2(20),
    FLAG            VARCHAR2(10),
    FAMILY          VARCHAR2(100),
    WRITING_SYSTEM  VARCHAR2(20),
    CONSTRAINT PK_LANGUAGES         PRIMARY KEY (ID),
    CONSTRAINT UQ_LANGUAGES_CODE    UNIQUE (CODE),
    CONSTRAINT CHK_LANGUAGES_WS     CHECK (WRITING_SYSTEM IN ('syllabary','alphabet','logogram','abugida'))
);
COMMIT;

-- ============================================================
--  2. USERS
--  NOTA: NAME y LEVEL son palabras reservadas en Oracle,
--        se renombran a FULL_NAME y USER_LEVEL
-- ============================================================
CREATE TABLE USERS (
    ID              NUMBER          GENERATED ALWAYS AS IDENTITY NOT NULL,
    USERNAME        VARCHAR2(50)    NOT NULL,
    FULL_NAME       VARCHAR2(100)   NOT NULL,
    EMAIL           VARCHAR2(150)   NOT NULL,
    USER_LEVEL      NUMBER(5)       DEFAULT 1,
    XP              NUMBER(10)      DEFAULT 0,
    TOTAL_XP        NUMBER(10)      DEFAULT 0,
    STREAK          NUMBER(5)       DEFAULT 0,
    JOIN_DATE       DATE            DEFAULT SYSDATE,
    CURRENT_LANG    NUMBER,
    CONSTRAINT PK_USERS             PRIMARY KEY (ID),
    CONSTRAINT UQ_USERS_USERNAME    UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL       UNIQUE (EMAIL),
    CONSTRAINT FK_USERS_LANG        FOREIGN KEY (CURRENT_LANG) REFERENCES LANGUAGES(ID)
);
COMMIT;

